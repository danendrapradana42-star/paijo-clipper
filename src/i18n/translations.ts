export const LOCALE_STORAGE_KEY = 'autoclipper.studio.locale.v1';

export function detectInitialLocale(): AppLocale {
  try {
    const saved = localStorage.getItem(LOCALE_STORAGE_KEY) as AppLocale | null;
    if (saved && APP_LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
  } catch {
    // ignore storage errors
  }

  if (typeof navigator !== 'undefined') {
    const prefs = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || ''];
    for (const raw of prefs) {
      const code = String(raw || '').toLowerCase().split('-')[0];
      if (code === 'ms') return 'id';
      const found = APP_LANGUAGES.find((l) => l.code === code);
      if (found) return found.code;
    }
  }
  return 'id';
}

